/* ================= Мелодии =================
   Формат нот: "НотаОктава:доли"  (например  E4:1  — ми первой октавы, одна доля)
   Все мелодии — классика, давно ставшая общественным достоянием.            */

function parseNotes(str) {
  return str.trim().split(/\s+/).map((tok) => {
    const [name, d] = tok.split(':');
    return { name, dur: parseFloat(d), midi: Piano.midi(name) };
  });
}

